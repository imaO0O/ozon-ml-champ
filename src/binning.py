"""Разбиение цели на бины: общее для сети и для бустинга.

Вынесено в отдельный модуль намеренно. Обе распределительные головы обязаны
резать цель ОДИНАКОВО, иначе их предсказания несравнимы между собой и
несравнимы с прежними прогонами. Держать две копии одной функции в seq_train
и в dist_gbm — это гарантированный расход: одна из них однажды поедет.

Модуль не тянет ни torch, ни lightgbm: бустинговый путь должен оставаться
запускаемым на машине без видеокарты, как обещано в README.
"""
from __future__ import annotations

import numpy as np


def bin_index(ylog: np.ndarray, edges: np.ndarray) -> np.ndarray:
    """Номер бина по таргету в log1p-шкале: 0 — ровно ноль, дальше по границам."""
    idx = 1 + np.searchsorted(edges, ylog, side="right")
    return np.where(ylog > 0, idx, 0).astype(np.int64)


def make_bins(train_y: list, n_bins: int):
    """Границы и центры бинов — по обучающим срезам, без валидационных таргетов.

    Нулю отводится ОТДЕЛЬНЫЙ бин, а не крайний квантильный: log1p(0) = 0 ровно,
    и там сидит около 46% клиентов. Смешать этот атом с малыми положительными
    значениями значило бы усреднить его с ними и потерять ровно то, ради чего
    голова и заводится.

    Остальные K-1 бинов режутся по квантилям положительной части, поэтому
    наполнены одинаково. Центр каждого — СРЕДНЕЕ log1p внутри него, а не
    середина отрезка: метрике нужна оценка среднего, а хвост скошен, и середина
    вносила бы смещение, растущее к правому краю.

    Совпавшие границы схлопываются: при тяжёлых совпадениях значений бинов
    окажется меньше заказанного, и это правильно — пустой бин с центром
    из воздуха хуже, чем честно меньшее число бинов.
    """
    y = np.concatenate([np.log1p(v) for v in train_y])
    pos = y[y > 0]
    if n_bins < 3 or len(pos) < n_bins:
        raise SystemExit(f"бинов {n_bins}: должно быть не меньше трёх "
                         f"и не больше числа положительных таргетов")
    edges = np.unique(np.quantile(pos, np.linspace(0, 1, n_bins)[1:-1]))
    idx = bin_index(y, edges)
    centers = np.zeros(len(edges) + 2, dtype=np.float64)
    for k in range(1, len(centers)):
        take = idx == k
        if not take.any():
            raise SystemExit(f"бин {k} пуст — квантили вырождены, уменьшите число бинов")
        centers[k] = y[take].mean()
    if not np.all(np.diff(centers) > 0):
        raise SystemExit("центры бинов не монотонны — дефект разбиения")
    return edges, centers
