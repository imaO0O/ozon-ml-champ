"""Печать в консоль, где нет половины математических знаков.

Русская Windows по умолчанию открывает консоль в cp1251, а в cp1251 нет ни
`−` (U+2212), ни `×`, ни `σ`, ни надстрочных цифр — при том что все они стоят
и в документах жюри, и в тексте, который печатают сами скрипты. Любая такая
строка валит скрипт `UnicodeEncodeError` **на печати**, то есть уже после
того, как работа сделана: замер прошёл, отчёт не вышел.

Замер 31.08 по `docs/jury/*.md` и `src/*.py`: **33 разных знака вне cp1251**,
из них `−` встречается в десяти питоновских файлах, `×` и `Δ` — ещё в трёх.
Воспроизводится одной строкой:

    cmd /c "chcp 1251 && python src/doc_audit.py"

Лечение — **не** перекодировать вывод в utf-8: в консоли cp1251 тогда посыплется
кириллица, а её здесь на порядок больше, чем греческих букв. Меняется только
политика ошибок: кодировка консоли остаётся своей, а непредставимый знак
печатается как `?`. Одна `?` вместо `×` лучше, чем трейсбек вместо отчёта.

Тот же приём, что с проверкой файла в `features.scan_log`: жюри не должно
видеть трейсбек там, где можно сказать словами. Разница в том, что там падало
до работы, а здесь — после неё, и потому обиднее.
"""
from __future__ import annotations

import sys


def relax(stream) -> None:
    """Разрешить потоку заменять непредставимые знаки вместо падения."""
    try:
        enc = (getattr(stream, "encoding", "") or "").lower().replace("-", "")
        if enc and enc != "utf8":
            stream.reconfigure(errors="replace")
    except Exception:
        # Поток без reconfigure (перехвачен тестом, подменён) — не наша беда:
        # настройка вывода не имеет права ронять то, что она защищает.
        pass


for _stream in (sys.stdout, sys.stderr):
    relax(_stream)
