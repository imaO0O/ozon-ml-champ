"""Плотная матрица `пользователь x день x канал` для последовательностных моделей.

Зачем отдельный формат. Бустингам нужны агрегаты, и `features/` считает их
ленивым `group_by`, не разворачивая сетку. Сети нужна ровно эта сетка: форма
поведения по дням, а не свёрнутые в суммы объёмы. Разворачивать её на каждый
cutoff заново — это ноутбук организаторов и его «40GB+ RAM»; вместо этого
матрица строится **один раз на весь период**, а срез любого cutoff'а получается
обычным слайсом по оси дней. Шесть обучающих срезов достаются бесплатно.

Размер: 250 000 x 409 x 18 в float16 — около 3.4 ГБ на диске. Читается как
`np.memmap`, поэтому в оперативную память целиком не поднимается: батч берёт
только свои строки, а горячая часть оседает в файловом кэше ОС.

Каналы, 18 штук тремя группами:

* 12 из лога — три денежных, семь счётчиков и два флага. Четыре флага `has_*`
  не хранятся: они выводятся из счётчиков (`has_x = x > 0`) и заняли бы треть
  объёма впустую. Деньги и счётчики кладутся в log1p, сеть получает величины
  одного порядка, а `expm1` для метрики нигде не нужен — таргет тоже в log1p;
* 3 доли в суточном объёме площадки (`share_*`);
* 3 дневных ранга среди активных этого дня (`rank_*`).

Имя файла содержит число каналов, поэтому матрица прежнего поколения на диске
не затирается и старые прогоны остаются воспроизводимыми.

Утечки будущего здесь нет по построению: матрица содержит только то, что было
в логе, а окно всегда обрывается на дне, предшествующем cutoff'у (см.
`window_bounds`). Ни одна функция этого модуля не смотрит на таргет.

    python -u src/seq_data.py            # собрать (или показать готовую)
    python -u src/seq_data.py --rebuild  # пересобрать с нуля
"""
from __future__ import annotations

import argparse
import datetime as dt
import time

import numpy as np
import polars as pl
from tqdm.auto import tqdm

from config import DATA_END, DATA_PROC, DATA_START, TRAIN_PARQUET
from features import scan_log

# Порядок каналов фиксирован: он попадает в веса обученной сети, менять его
# задним числом нельзя — иначе старые чекпойнты молча начнут читать не те данные.
RAW_CHANNELS = [
    "gmv", "gmv_search", "gmv_cat",                     # деньги
    "to_ord", "to_cart", "searches",                    # счётчики общие
    "search_to_ord", "search_to_cart",                  # счётчики поиска
    "cat_to_ord", "cat_to_cart",                        # счётчики каталога
    "search", "cat",                                    # флаги «был в поиске / каталоге»
]
LOG_CHANNELS = RAW_CHANNELS[:10]  # флаги в log1p не переводим — они и так 0/1

# Доли пользователя в суточном объёме площадки. Зачем они здесь: сеть,
# обученная на абсолютных рублях, промахивается по уровню тестового окна
# на +0.20 в log1p, тогда как бустинг — только на -0.058. Разница ровно в том,
# что у бустинга есть блок `platform` с долями, а у сети не было ничего.
# Уровень площадки за год менялся вдвое, а доля от него не зависит.
#
# Утечки нет: суточный итог за день D считается по событиям дня D, а окно
# всегда обрывается на дне перед cutoff'ом — значит в него попадают только дни,
# целиком лежащие в прошлом.
#
# Доли масштабируются на число пользователей: сырая доля порядка 1e-5 попала бы
# в субнормальный диапазон float16 и потеряла бы точность. После умножения
# единица означает «вклад среднего пользователя за этот день».
SHARE_CHANNELS = ["share_gmv", "share_ord", "share_searches"]
SHARE_SOURCE = [("gmv", "day_gmv"), ("to_ord", "day_ord"), ("searches", "day_searches")]

# Ранг клиента среди активных этого дня — второй уровнеустойчивый взгляд на те
# же три величины, что и доли. Зачем оба: доля тянется тяжёлыми клиентами
# (один заказ на миллион перекашивает знаменатель), ранг к этому невосприимчив,
# потому что смотрит на порядок, а не на величину.
#
# Почему именно ранги. Из всех проверенных смен представления входа сработала
# ровно одна — статические ранги блока `ranks`, — и она единственная
# ДОБАВЛЯЛА уровнеустойчивый взгляд, тогда как события и нормировка на
# собственную историю информацию убирали и обе провалились. Плюс замер
# нормировки показал, чем отличается работающий делитель от неработающего:
# он должен быть оценён надёжно. Ранг по 250 000 клиентов — порядковая
# статистика, надёжнее некуда, в отличие от среднего темпа одного клиента.
#
# Разница со статическими рангами: те одно число на всё окно, эти — форма,
# ранг меняется день ото дня и показывает, поднимается клиент относительно
# площадки или опускается.
#
# Ранг в [0, 1], 1 — самый крупный за день. Отсутствующий в этот день клиент
# получает 0, как и по всем остальным каналам: отдельного «нет данных» здесь
# не заводим, его несёт канал `observed` окна.
#
# ПРОВЕРЕНО И ПРИНЯТО — первое подтверждённое улучшение сети после рангов.
# Против контрольной руки на той же матрице (--no-day-ranks), уровень выровнен,
# ШЕСТЬ срезов, по три сида на руку (разбор — src/density_gain.py):
#
#     2025-08-18  +0.00258      2025-11-16  +0.00078
#     2025-09-17  +0.00240      2025-12-16  +0.00129
#     2025-10-17  +0.00163      2026-01-15  +0.00141
#
# Положителен везде, среднее +0.00168, Gini тоже растёт на всех шести. В
# оптимальном составе вес крупный (0.41-0.46), у контрольной руки при этом
# отрицательный: дневные ранги плотную сеть не дополняют, а вытесняют.
#
# Как это мерили сначала и почему получилось иначе. Одиночные прогоны давали
# +0.00421 на январе и +0.00036 на декабре — разброс вдесятеро, из которого мы
# вывели «асимметрию» и объяснили её ростом плотности сетки. На трёх сидах
# разброс исчез: он был шумом сида, а не свойством срезов. Гипотеза плотности
# отдельно проверена на шести точках и опровергнута знаком (корреляция -0.766).
#
# Отсюда правило, стоявшее рядом с ловушкой уровня: одиночный прогон сети не
# измеряет ничего порядка тысячных. Три сида стоят втрое дороже и снимают как
# ложные эффекты, так и ложные объяснения к ним.
#
# ПОПРАВКА, после починки критерия ранней остановки. Правило было верным, но
# причина оказалась не в сидах. Разброс трёх сидов на одном срезе:
#
#     сломанная остановка (по сырой метрике)   выровненный разброс 0.00283
#     починенная (по выровненной)              выровненный разброс 0.00022
#
# В тринадцать раз. Сиды сами по себе почти не расходятся — расходился ВЫБОР
# ЭПОХИ: критерий судил по величине с уровнем внутри, и каждый сид
# останавливался в случайном месте кривой. Сырой разброс при этом даже вырос
# (0.00207 -> 0.00317), потому что починенный критерий больше не подгоняет
# уровень, — но сырая величина и не наша метрика.
#
# Практический итог: порог значимости для сети упал с ~0.003 до ~0.0002.
# Часть направлений, закрытых как "неотличимо от нуля", закрывалась при пороге
# вчетверо-впятеро выше настоящего.
#
# Осторожно с сырыми числами: сиды расходятся по уровню сильно (сдвиги -0.034,
# +0.054, -0.029 у трёх финальных прогонов), и по сырому RMSLE разброс между
# ними 0.0043 против 0.0007 после выравнивания. Усреднение трёх сидов гасит
# уровень само: у gru_dr90_avg3 остаточный сдвиг -0.00275.
# Три канала — деньги, заказы, поиски. Ровно три, и это проверено:
#
# РАСШИРЕНИЕ ДО ШЕСТИ ОТВЕРГНУТО. Пробовали добавить to_cart (намерение вместо
# покупки), search_to_ord и cat_to_ord (расщепление заказов по источнику) —
# каналы, выбранные так, чтобы не дублировать первые три. Шесть срезов, три
# сида на срез, уровень выровнен:
#
#     срез        без рангов   3 ранга   6 рангов    3-0        6-3
#     2026-01-15    1.67255   1.67113   1.67145   +0.00141   -0.00031
#     2025-12-16    1.73883   1.73754   1.73827   +0.00129   -0.00073
#     2025-11-16    1.73516   1.73438   1.73362   +0.00078   +0.00076
#     2025-10-17    1.71360   1.71197   1.71219   +0.00163   -0.00022
#     2025-09-17    1.72626   1.72386   1.72461   +0.00240   -0.00075
#     2025-08-18    1.74757   1.74500   1.74355   +0.00258   +0.00145
#     среднее                                     +0.00168   +0.00003
#     положительно                                     6/6        2/6
#
# Переход от нуля рангов к трём стоит 0.00168 и положителен везде. Переход от
# трёх к шести стоит ноль. Это насыщение, а не случайность: заказы из поиска
# плюс заказы из каталога складываются в заказы, ранг которых уже есть, — новые
# каналы несут ту же информацию в другой раскладке.
#
# Правило на будущее, если кто-то захочет продолжить: добавление
# уровнеустойчивого взгляда работает только пока взгляд НОВЫЙ. Расщепление уже
# взятой величины новым взглядом не является.
#
# Остальные каналы не пробовали намеренно: gmv_search и gmv_cat почти повторяют
# gmv по порядку, флаги двоичны и ранг по ним вырождается в долю активных.
RANK_CHANNELS = ["rank_gmv", "rank_ord", "rank_searches"]
RANK_SOURCE = ["gmv", "to_ord", "searches"]

# Каналы первого прохода: всё, что берётся из строки лога напрямую. Дневные
# ранги сюда не входят — их считает fill_day_ranks вторым проходом, потому что
# ранг берётся по столбцу матрицы, а первый проход идёт по строкам.
BASE_CHANNELS = RAW_CHANNELS + SHARE_CHANNELS

CHANNELS = BASE_CHANNELS + RANK_CHANNELS

# Как сворачивать канал при укрупнении шага (см. --bin в seq_train). Величины
# складываются в исходной шкале — «сколько всего за неделю», — а флаги
# усредняются: «в какой доле дней недели пользователь заходил».
SUM_CHANNELS = LOG_CHANNELS + SHARE_CHANNELS
MEAN_CHANNELS = [c for c in CHANNELS if c not in SUM_CHANNELS]

N_DAYS = (DATA_END - DATA_START).days + 1
N_CHANNELS = len(CHANNELS)


def seq_path() -> "tuple":
    """Матрица и её спутник с индексом пользователей.

    Имя включает источник данных (реальные/синтетика) и форму, поэтому прогон
    на `fake_train.parquet` не затрёт настоящую матрицу и наоборот.
    """
    stem = f"seq_{TRAIN_PARQUET.stem}_{N_DAYS}x{N_CHANNELS}"
    return DATA_PROC / f"{stem}.npy", DATA_PROC / f"{stem}.meta.npz"


def day_index(d: dt.date) -> int:
    """Номер дня в матрице. Для cutoff'а это индекс *первого неизвестного* дня."""
    return (d - DATA_START).days


def window_bounds(cutoff: dt.date, lookback: int) -> "tuple[int, int]":
    """Границы окна `[d0, d1)` строго до cutoff'а. d0 может быть отрицательным.

    d1 = day_index(cutoff) — сам день cutoff'а в окно не входит: таргет считается
    начиная с него, и попадание этого дня в признаки было бы утечкой.
    Отрицательный d0 означает, что окно длиннее доступной истории; недостающие
    дни добиваются нулями, а канал `observed` отличает их от настоящего затишья.
    """
    d1 = day_index(cutoff)
    return d1 - lookback, d1


def fill_day_ranks(arr, users: np.ndarray, lf, date_chunks: int = 6) -> None:
    """Дописать в матрицу дневные ранги — вторым проходом, по датам.

    Почему отдельным проходом. Ранг считается среди всех активных клиентов
    одного дня, то есть по столбцу матрицы, а основная сборка идёт по
    диапазонам пользователей — по строкам. Внутри куска пользователей нужных
    данных попросту нет.

    Внутри куска дат строки сортируются по user_id: раскладка C-порядковая,
    и без сортировки запись прыгала бы случайными точками по всему файлу.
    После сортировки каждый пользователь трогается подряд, и страница его
    истории поднимается один раз, а не по разу на день.
    """
    edges = np.linspace(0, N_DAYS, date_chunks + 1).astype(np.int64)
    base = len(BASE_CHANNELS)
    prog = tqdm(total=date_chunks, desc="  дневные ранги", unit="кусок", disable=None,
                leave=False, dynamic_ncols=True)
    for i in range(date_chunks):
        d_lo, d_hi = int(edges[i]), int(edges[i + 1])
        if d_lo == d_hi:
            continue
        lo_date = DATA_START + dt.timedelta(days=d_lo)
        hi_date = DATA_START + dt.timedelta(days=d_hi - 1)
        df = (
            lf.filter((pl.col("event_date") >= pl.lit(lo_date))
                      & (pl.col("event_date") <= pl.lit(hi_date)))
            .with_columns(
                (pl.col("event_date") - pl.lit(DATA_START)).dt.total_days().cast(pl.Int32).alias("_d"),
                # rank/count, а не rank/max: при равных значениях средний ранг
                # делится на число активных, и шкала остаётся [0, 1] на любом дне.
                *[(pl.col(src).rank(method="average").over("event_date")
                   / pl.len().over("event_date")).cast(pl.Float32).alias(name)
                  for name, src in zip(RANK_CHANNELS, RANK_SOURCE)],
            )
            .select(["user_id", "_d", *RANK_CHANNELS])
            .sort("user_id")
            .collect(engine="streaming")
        )
        if df.height == 0:
            continue
        ui = np.searchsorted(users, df["user_id"].to_numpy())
        di = df["_d"].to_numpy()
        arr[ui, di, base:base + len(RANK_CHANNELS)] = (
            df.select(RANK_CHANNELS).to_numpy().astype(np.float16))
        prog.set_postfix_str(f"дни {d_lo}..{d_hi}, строк {df.height:,}")
        prog.update(1)
        del df, ui, di
    prog.close()


def build(rebuild: bool = False, chunks: int = 8) -> "tuple":
    """Собрать матрицу. Возвращает (memmap, user_ids, first_day, last_day).

    Пишется по диапазонам пользователей, а не по датам: раскладка массива
    C-порядковая, поэтому вся история одного пользователя лежит в файле подряд,
    и запись диапазоном идёт последовательно, а не случайными точками по 2.5 ГБ.
    """
    path, meta_path = seq_path()
    if path.exists() and meta_path.exists() and not rebuild:
        return open_seq()

    lf = scan_log()
    t0 = time.time()
    users = (
        lf.select(pl.col("user_id").unique())
        .collect(engine="streaming")["user_id"]
        .sort()
        .to_numpy()
    )
    n_users = len(users)
    print(f"пользователей в логе: {n_users:,} | дней: {N_DAYS} | каналов: {N_CHANNELS}")
    print(f"размер матрицы: {n_users * N_DAYS * N_CHANNELS * 2 / 1024 ** 3:.2f} ГБ (float16)")

    # Границы активности каждого пользователя — одним проходом, чтобы потом не
    # пересчитывать «есть ли история до cutoff'а» по самой матрице.
    bounds = (
        lf.with_columns(
            (pl.col("event_date") - pl.lit(DATA_START)).dt.total_days().cast(pl.Int32).alias("d")
        )
        .group_by("user_id")
        .agg(pl.col("d").min().alias("first"), pl.col("d").max().alias("last"))
        .collect(engine="streaming")
        .sort("user_id")
    )
    first_day = bounds["first"].to_numpy().astype(np.int32)
    last_day = bounds["last"].to_numpy().astype(np.int32)

    # Суточные итоги площадки — 409 строк, считаются одним проходом по всем
    # пользователям и затем подмешиваются в каждый кусок.
    day_tot = (
        lf.group_by("event_date")
        .agg(pl.col("gmv").sum().alias("day_gmv"),
             pl.col("to_ord").sum().alias("day_ord"),
             pl.col("searches").sum().alias("day_searches"))
        .collect(engine="streaming")
    )
    print(f"суточные итоги площадки: {day_tot.height} дней")

    arr = np.lib.format.open_memmap(
        path, mode="w+", dtype=np.float16, shape=(n_users, N_DAYS, N_CHANNELS)
    )

    edges = np.linspace(0, n_users, chunks + 1).astype(np.int64)
    rows_total = 0
    # disable=None — tqdm гасит себя, когда вывод не в терминал: сборка часто
    # запускается фоном, и в логе возвраты каретки только мешают.
    prog = tqdm(total=chunks, desc="  сборка матрицы", unit="кусок", disable=None,
                leave=False, dynamic_ncols=True)
    for i in range(chunks):
        lo, hi = int(edges[i]), int(edges[i + 1])
        if lo == hi:
            continue
        u_lo, u_hi = int(users[lo]), int(users[hi - 1])
        df = (
            lf.filter((pl.col("user_id") >= u_lo) & (pl.col("user_id") <= u_hi))
            .join(day_tot.lazy(), on="event_date", how="left")
            .with_columns(
                (pl.col("event_date") - pl.lit(DATA_START)).dt.total_days().cast(pl.Int32).alias("_d"),
                # Доли считаются ДО log1p исходных колонок, иначе в числителе
                # окажется логарифм вместо самой величины.
                *[(pl.col(num) / (pl.col(den) + 1e-9) * n_users).cast(pl.Float32).log1p().alias(name)
                  for name, (num, den) in zip(SHARE_CHANNELS, SHARE_SOURCE)],
            )
            .with_columns(*[pl.col(c).cast(pl.Float32).log1p() for c in LOG_CHANNELS])
            .select(["user_id", "_d", *BASE_CHANNELS])
            .collect(engine="streaming")
        )
        if df.height == 0:
            continue
        # searchsorted, а не join: users отсортирован, и это дешевле любого join'а.
        ui = np.searchsorted(users, df["user_id"].to_numpy())
        di = df["_d"].to_numpy()
        vals = df.select(BASE_CHANNELS).to_numpy().astype(np.float16)
        arr[ui, di, :len(BASE_CHANNELS)] = vals
        rows_total += df.height
        prog.set_postfix_str(f"пользователи {lo:,}..{hi:,}, строк {df.height:,}")
        prog.update(1)
        del df, ui, di, vals

    prog.close()
    fill_day_ranks(arr, users, lf)
    arr.flush()
    np.savez(meta_path, users=users, first_day=first_day, last_day=last_day,
             channels=np.array(CHANNELS), n_days=N_DAYS)
    dens = rows_total / (n_users * N_DAYS)
    print(f"\n{path}")
    print(f"строк лога: {rows_total:,} | заполненность сетки: {dens:.1%} | "
          f"{time.time() - t0:.0f}s")
    return open_seq()


def open_seq() -> "tuple":
    """Открыть готовую матрицу только на чтение."""
    path, meta_path = seq_path()
    if not (path.exists() and meta_path.exists()):
        raise SystemExit(f"нет матрицы {path.name} — соберите: python -u src/seq_data.py")
    meta = np.load(meta_path, allow_pickle=False)
    arr = np.load(path, mmap_mode="r")
    return arr, meta["users"], meta["first_day"], meta["last_day"]


def gather(seq, rows: np.ndarray, cutoff: dt.date, lookback: int) -> np.ndarray:
    """Окна нескольких пользователей: (len(rows), lookback, N_CHANNELS + 1).

    Последний канал — `observed`: 1 для дней, попавших в наблюдаемый период,
    0 для добитых нулями. Без него сеть не отличает «пользователь молчал» от
    «данных за этот день вообще нет», а это разные вещи: у старых срезов история
    короче, чем у тестового (229 дней против 409), и без явного признака модель
    выучила бы эту разницу как поведение клиента.
    """
    d0, d1 = window_bounds(cutoff, lookback)
    n = len(rows)
    out = np.zeros((n, lookback, N_CHANNELS + 1), dtype=np.float32)
    pad = max(0, -d0)
    src_lo = max(0, d0)
    if d1 > src_lo:
        out[:, pad:, :N_CHANNELS] = seq[rows, src_lo:d1]
        out[:, pad:, N_CHANNELS] = 1.0
    return out


def self_norm(win: np.ndarray) -> np.ndarray:
    """Поделить каналы клиента на его же средний уровень: форма вместо масштаба.

    Зачем. Бленду нужна непохожесть, а не второй сильный участник: событийное
    представление это показало от обратного — оно получило в оптимальном
    составе отрицательный вес именно потому, что было той же моделью, только
    хуже. Значит менять надо не длину и не архитектуру, а то, **чем сеть
    является относительно бустинга**.

    Масштаб клиента бустинг ловит прямо: `gmv_sum_90`, `avg_check`, ранги — всё
    это про «сколько». Сеть, обученная на тех же абсолютных величинах, тратит
    ёмкость на повторение того, что уже посчитано точнее. После деления каждого
    канала на его собственное среднее по окну у сети остаётся только форма и
    тайминг: когда клиент активен относительно своего обычного, разгоняется он
    или затухает. Это то, чего в признаках бустинга нет вовсе.

    Масштаб при этом не теряется — он приходит статической веткой: 27 рангов
    блока `ranks` несут «сколько» в виде, устойчивом к сдвигу уровня площадки.
    Разделение получается чистое: последовательность отвечает за форму, ранги
    за величину.

    Нормируются 10 логарифмических каналов, каждый на своё среднее. Общий
    делитель был бы неверен размерностно: делить поисковые запросы на рубли
    нельзя. Флаги `search`/`cat` остаются 0/1, доли площадки — уже безразмерные
    и нормируются площадкой, а не клиентом.

    Клиент, ни разу не сделавший действие, даёт по этому каналу нули: деление
    оставляет нули, отдельная ветка не нужна.

    Утечки нет: среднее считается по тому же окну, что и сам вход, а окно
    обрывается на дне перед cutoff'ом.

    ПРОВЕРЕНО И ОТВЕРГНУТО, вместе со --static rk_ на обоих срезах:

        январь (выровнено)  сетка 1.67292 -> нормировка 1.67760   -0.00468
        декабрь             сетка 1.73735 -> нормировка 1.74787   -0.01052

    В оптимальном составе вес **-0.197**. Расчёт «сеть отдаёт масштаб рангам и
    занимается только формой» не оправдался: ранги масштаб несут, но сеть без
    абсолютных величин не стала непохожей — она стала просто хуже. Декабрьский
    прогон вдобавок скакал от 1.74787 до 1.79266 между эпохами: нормированный
    вход заметно менее устойчив в обучении.

    Общий вывод по трём попыткам сменить представление входа — он же причина
    закрыть направление целиком. События, события с годом истории и эта
    нормировка все три оказались хуже и все три получили в составе
    ОТРИЦАТЕЛЬНЫЙ вес. Общее у них одно: каждая **убирала** информацию —
    события выбросили структуру пустых дней, нормировка выбросила масштаб, —
    и в обоих случаях предполагалось, что убранное компенсируется другим
    каналом (`gap`, ранги). Не компенсировалось ни разу.

    А единственная смена представления, которая за всю работу сработала, —
    ранги на статическом входе — наоборот **добавляла**: устойчивый к сдвигу
    уровня взгляд на ту же величину. Отсюда правило для тех, кто продолжит:
    добавлять уровнеустойчивый взгляд стоит, убирать информацию ради
    непохожести — нет. По этой же причине не стоит тратить прогон на деление
    дневной величины на дневной уровень площадки: это тоже убирание.
    """
    idx = list(range(len(LOG_CHANNELS)))
    out = win.astype(np.float32, copy=True)
    v = np.expm1(out[:, :, idx])
    m = v.mean(axis=1, keepdims=True)
    out[:, :, idx] = np.log1p(v / np.maximum(m, 1e-6))
    return out


def events_window(win: np.ndarray, n_tokens: int) -> np.ndarray:
    """Дневную сетку — в последовательность событий: (len(rows), n_tokens, C + 3).

    Зачем. В окне 90 дней у медианного клиента активны 30, в окне 180 — 55;
    63–65% дневной сетки это нули, и рекуррентность тратится на их пробегание.
    Промежуток между покупками при этом закодирован **неявно** — длиной пробега
    нулей, которую сеть обязана посчитать сама. Здесь он становится числом.

    Почему это важнее, чем экономия шагов. Разложение роста площадки показывает,
    что GMV на зарегистрированного клиента за 30 дней вырос с 58 до 111, а GMV
    на активного клиента в день остался плоским: 8.46 против 8.53. Рост — это
    **частота появлений, а не размер чека**, то есть дрейф между обучающими
    срезами и тестом сидит ровно в длинах промежутков. На плотной сетке модель
    видит его косвенно, здесь — прямо, отдельным каналом.

    Побочно вход втрое короче: те же 180 дней истории укладываются в ~55 токенов,
    а бюджет в 128 токенов покрывает больше года.

    Три добавленных канала после C данных:

    * `valid` — 1 у настоящего токена, 0 у добивки слева (у клиентов с малым
      числом активных дней последовательность короче бюджета);
    * `age` — log1p дней от события до cutoff'а, то есть рецентность в явном
      виде, а не позицией в последовательности;
    * `gap` — log1p дней с прошлого события; у самого старого токена это
      расстояние до начала окна, то есть длина молчания перед ним.

    Токены выровнены вправо: самое свежее событие всегда в последнем слоте.
    Это тот же порядок, что у плотной сетки, поэтому голова с пулом последнего
    состояния продолжает читать «что происходит прямо перед cutoff'ом».

    При переполнении бюджета берутся **свежие** события: «свежесть важнее
    количества» подтверждена в этой задаче трижды.

    Оговорка. Канал `observed` из `gather` здесь не переносится: все токены по
    построению наблюдаемые. Разницу «истории не было» против «клиент молчал»
    несёт `gap` у старейшего токена — величина разная, но не помеченная. Для
    старых срезов с короткой историей это слабее явного флага.

    ПРОВЕРЕНО И ОТВЕРГНУТО. Оба среза, уровень выровнен, декабрь досошёлся:

        январь   сетка 1.67292 -> события 1.67413   -0.00121
        декабрь  сетка 1.73735 -> события 1.73913   -0.00178
        январь, год истории в 96 токенах  1.67614   -0.00322

    Знак не меняется, величина одного порядка — это настоящий минус, а не шум.
    Решает даже не он: в оптимальном составе событийная сеть получает вес
    **-0.146**, то есть она не непохожий участник, а худшая копия сетки, и
    бленду не нужна ни в каком количестве. Год истории тоже не окупился —
    длина не была узким местом.

    Почему не сработало. Механизм «сеть тратит рекуррентность на пробегание
    нулей» не подтвердился: train RMSE держится на тех же 1.734-1.739, что и на
    плотной сетке, то есть предел лежит не в длине последовательности. А цена
    оказалась в том, что шаг перестал быть равномерным: обычный GRU принимает
    `gap` как ещё один признак, но не умеет затухать состоянием пропорционально
    ему — для неравномерных рядов это делается гейтом в самой рекуррентности
    (time-decay), а не каналом на входе. Каналом мы дали информацию, но не дали
    механизма ею воспользоваться.

    Что здесь всё же полезного. Отчёт `seq_data.py --events N` показал прямой
    замер дрейфа частоты: плотность непустых дней растёт монотонно от среза к
    срезу, 24.5% в августе -> 28.4% в январе -> 29.2% на тесте. Тестовое окно
    плотнее любого обучающего. Нулей при этом 71-76%, а не 63-65%.
    """
    n, lookback, c_in = win.shape
    n_raw = len(RAW_CHANNELS)
    c = c_in - 1  # канал observed не переносится, см. оговорку выше
    dat = win[:, :, :c]

    active = (dat[:, :, :n_raw] != 0).any(axis=2)
    # Ранг с конца: 1 у самого свежего активного дня. Бюджет режет старые.
    rank = np.cumsum(active[:, ::-1], axis=1)[:, ::-1]
    keep = active & (rank <= n_tokens)
    slot = n_tokens - rank

    out = np.zeros((n, n_tokens, c + 3), dtype=np.float32)
    b, d = np.nonzero(keep)
    s = slot[b, d]
    out[b, s, :c] = dat[b, d]
    out[b, s, c] = 1.0

    # d = lookback - 1 — день накануне cutoff'а, его возраст 1 день.
    age = np.zeros((n, n_tokens), dtype=np.float32)
    age[b, s] = lookback - d
    out[:, :, c + 1] = np.log1p(age)

    valid = out[:, :, c] > 0
    prev_age = np.zeros_like(age)
    prev_age[:, 1:] = age[:, :-1]
    prev_valid = np.zeros_like(valid)
    prev_valid[:, 1:] = valid[:, :-1]
    # У старейшего токена предыдущего события нет: берём расстояние до начала
    # окна, lookback - age = число дней молчания перед ним.
    gap = np.where(prev_valid, prev_age - age, lookback - age)
    out[:, :, c + 2] = np.log1p(np.clip(gap, 0, None)) * valid
    return out


def history_mask(first_day: np.ndarray, cutoff: dt.date) -> np.ndarray:
    """Пользователи, у которых есть хотя бы одно событие до cutoff'а.

    Это ровно тот набор, на котором обучается и меряется бустинг: `build_features`
    оставляет пользователей с непустой историей, а `predict.py` добивает
    остальных нулями уже на этапе сабмита.
    """
    return first_day < day_index(cutoff)


def report_events(n_tokens: int, lookback: int, sample: int = 40000,
                  chunk: int = 4000) -> None:
    """Сколько токенов на самом деле нужно: распределение активных дней в окне.

    Бюджет выбирается не на глаз: слишком маленький режет историю у активных
    клиентов, слишком большой возвращает добивку нулями, ради избавления от
    которой всё и затевалось.

    Окна берутся кусками: `gather` разворачивает плотный float32, и выборка
    целиком — это гигабайты сверх самой матрицы.
    """
    from config import TEST_CUTOFF, train_cutoffs

    seq, users, first_day, _ = build()
    rng = np.random.default_rng(0)
    n_raw = len(RAW_CHANNELS)

    print(f"окно {lookback} дней, бюджет {n_tokens} токенов, выборка {sample:,}\n")
    print(f"{'срез':<14}{'активных дней':>26}{'плотность':>11}{'переполнили':>13}")
    for cutoff in train_cutoffs(6) + [TEST_CUTOFF]:
        rows = np.nonzero(history_mask(first_day, cutoff))[0]
        sel = np.sort(rng.choice(rows, size=min(sample, len(rows)), replace=False))
        act = np.concatenate([
            (gather(seq, sel[i:i + chunk], cutoff, lookback)[:, :, :n_raw] != 0)
            .any(axis=2).sum(axis=1)
            for i in range(0, len(sel), chunk)])
        q = np.percentile(act, [25, 50, 75])
        print(f"{str(cutoff):<14}"
              f"{f'{q[0]:.0f} / {q[1]:.0f} / {q[2]:.0f}':>26}"
              f"{act.mean() / lookback:>10.1%}{(act > n_tokens).mean():>13.1%}")
    print("\nактивных дней — квартили 25 / 50 / 75; плотность — доля непустых дней")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--events", type=int, default=0,
                    help="не собирать матрицу, а показать, сколько токенов нужно "
                         "событийному представлению при таком бюджете")
    ap.add_argument("--lookback", type=int, default=180,
                    help="длина окна для отчёта --events")
    ap.add_argument("--rebuild", action="store_true")
    ap.add_argument("--chunks", type=int, default=8,
                    help="на сколько диапазонов пользователей резать проход (меньше = больше RAM)")
    args = ap.parse_args()

    if args.events:
        report_events(args.events, args.lookback)
        return

    seq, users, first_day, last_day = build(rebuild=args.rebuild, chunks=args.chunks)
    print(f"\nматрица: {seq.shape} {seq.dtype}")
    print(f"пользователей: {len(users):,} | первый день активности: медиана {np.median(first_day):.0f}")
    from config import TEST_CUTOFF, train_cutoffs

    for c in train_cutoffs(6) + [TEST_CUTOFF]:
        d0, d1 = window_bounds(c, 180)
        print(f"  {c}: окно 180 дней -> дни [{d0}, {d1}) | "
              f"с историей {history_mask(first_day, c).sum():,}")


if __name__ == "__main__":
    main()
