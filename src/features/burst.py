"""Концентрация активности во времени: как размазаны покупки по дням.

Чего в признаках не было. Проверено прямым перечислением всех 242 колонок:
ни одного признака концентрации — ни индекса Херфиндаля, ни доли лучшего дня,
ни энтропии распределения по дням недели. Есть `gmv_max_W` и `gmv_sum_W`,
но их отношение — это только вершина распределения, а не его форма.

Почему это НЕ пересказ уже взятого. Оконные агрегаты отвечают на вопрос
«сколько всего», ранги — «где среди всех», тренды — «растёт или падает».
Ни один не отвечает «в один день или равномерно». Клиент с 30 000 за один день
и клиент с теми же 30 000 по тысяче за тридцать дней имеют одинаковые суммы,
одинаковые ранги и одинаковые тренды, а ведут себя противоположно: первый
сделал разовую крупную покупку, второй покупает регулярно. Для предсказания
следующих 30 дней это разные истории.

Почему признаки устойчивы к уровню площадки. Все они — **отношения** внутри
клиента: доли, индексы концентрации, энтропия. Уровень площадки за год менялся
вдвое, и абсолютные величины из-за этого плывут (см. блок `ranks`), а доли —
нет. Это то же свойство, которое сделало ранги единственным сработавшим
семейством представления.

Утечки будущего нет: всё считается по `days_ago >= 1`, то есть строго до среза.
"""
from __future__ import annotations

import datetime as dt

import polars as pl

from .registry import aggs_block, derived_block

EPS = 1e-9
WINDOWS = (30, 90, 365)


def _hhi(col: str, days: int) -> pl.Expr:
    """Индекс Херфиндаля по дневным значениям внутри окна.

    Лог уже дневной — одна строка на клиента и день, — поэтому внутри
    `group_by("user_id")` значения и есть дневные, и сумма квадратов долей
    считается напрямую. 1.0 означает «всё в один день», 1/n — «поровну
    по n дням».
    """
    v = pl.col(col).filter(pl.col("days_ago") <= days)
    return ((v ** 2).sum() / ((v.sum() ** 2) + EPS)).alias(f"hhi_{col}_{days}")


@aggs_block("burst")
def burst_aggs(cutoff: dt.date) -> list[pl.Expr]:
    out: list[pl.Expr] = []
    for d in WINDOWS:
        out.append(_hhi("gmv", d))
        out.append(_hhi("to_ord", d))
        # Размах активности: между первым и последним активным днём окна.
        # Вместе с числом активных дней даёт плотность, а не только объём.
        ago = pl.col("days_ago").filter(pl.col("days_ago") <= d)
        out.append((ago.max() - ago.min()).alias(f"span_{d}"))
        # Доля дней окна, в которые была покупка, среди активных дней.
        act = pl.col("days_ago").filter((pl.col("days_ago") <= d)).n_unique()
        buy = pl.col("days_ago").filter((pl.col("days_ago") <= d)
                                        & (pl.col("gmv") > 0)).n_unique()
        out.append((buy / (act + EPS)).alias(f"buyday_rate_{d}"))

    # Профиль по дням недели за 90 дней: концентрация и любимый день.
    # Тестовое окно состоит из другого набора дней недели, чем обучающие
    # (PLAN, раздел 5а), поэтому профиль клиента может взаимодействовать
    # с составом окна — этого взаимодействия у модели до сих пор не было.
    dow = pl.col("event_date").dt.weekday()
    for i in range(1, 8):
        g = pl.col("gmv").filter((pl.col("days_ago") <= 90) & (dow == i)).sum()
        out.append(g.alias(f"dow{i}_gmv_90"))
    return out


@derived_block("burst")
def burst_derived() -> list[pl.Expr]:
    out: list[pl.Expr] = []
    for d in WINDOWS:
        # Плотность активности внутри своего же размаха: 1.0 — каждый день
        # подряд, 0.1 — редкие всплески на длинном промежутке.
        out.append((pl.col(f"active_days_{d}" if d != 365 else "active_days_365")
                    / (pl.col(f"span_{d}") + 1.0))
                   .alias(f"density_{d}"))
    tot = sum(pl.col(f"dow{i}_gmv_90") for i in range(1, 8)) + EPS
    shares = [(pl.col(f"dow{i}_gmv_90") / tot) for i in range(1, 8)]
    # Концентрация по дням недели: 1/7 — ровно, 1.0 — всё в один день недели.
    out.append(sum(s ** 2 for s in shares).alias("dow_hhi_90"))
    out.append(pl.max_horizontal([s.alias(f"_s{i}") for i, s in enumerate(shares)])
               .alias("dow_top_share_90"))
    return out
